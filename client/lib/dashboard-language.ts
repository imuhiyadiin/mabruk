const englishText = Object.fromEntries(Object.entries(somaliText).map(([english, somali]) => [somali, english]));

function translated(value: string, language: DashboardLanguage) {
  const dictionary = language === "SO" ? somaliText : englishText;
  const trimmed = value.trim();
  const replacement = dictionary[trimmed];
  if (!replacement) return value;
  const leading = value.match(/^\s*/)?.[0] ?? "";
  const trailing = value.match(/\s*$/)?.[0] ?? "";
  return `${leading}${replacement}${trailing}`;
}

export function translateDashboard(root: HTMLElement, language: DashboardLanguage) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node: Node | null;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (!parent || parent.closest("script, style, textarea, input, svg")) continue;
    const value = node.nodeValue ?? "";
    const replacement = translated(value, language);
    if (replacement !== value) node.nodeValue = replacement;
  }

  root.querySelectorAll<HTMLElement>("*").forEach((element) => {
    for (const attribute of ["placeholder", "title", "aria-label"]) {
      const value = element.getAttribute(attribute);
      if (!value) continue;
      const replacement = translated(value, language);
      if (replacement !== value) element.setAttribute(attribute, replacement);
    }
  });
}
